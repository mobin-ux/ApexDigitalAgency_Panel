#!/usr/bin/env bash
# ============================================================================
#  Apex Digi — keep Caddy's list of Cloudflare addresses current (ADR-023)
# ============================================================================
#  Runs ON THE SERVER. Writes /etc/caddy/cloudflare-ips.caddy, the file that
#  deploy/Caddyfile imports into its `servers` block:
#
#      trusted_proxies static <every Cloudflare IPv4 and IPv6 range>
#
#  Only a request from one of these ranges may tell Caddy who the real client
#  is (Cf-Connecting-Ip); everything else is treated as the client itself.
#
#  Usage:
#      bash cloudflare-ips.sh              # refresh; reload Caddy if it changed
#      bash cloudflare-ips.sh --no-reload  # refresh the file only
#      bash cloudflare-ips.sh --check      # print what would change, write nothing
#
#  Cloudflare publishes the ranges at https://www.cloudflare.com/ips-v4 and
#  /ips-v6; they change a few times a year. scripts/ship-caddy.sh installs a
#  weekly systemd timer that runs this script, so a new range never leaves
#  visitors sharing one rate-limit bucket.
# ============================================================================
set -euo pipefail

OUT="${CF_IPS_FILE:-/etc/caddy/cloudflare-ips.caddy}"
MODE="${1:-}"

v4="$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4)"
v6="$(curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6)"

# A list that is suddenly tiny means a broken download, not a smaller
# Cloudflare: refuse rather than shrink the trusted set to nothing.
n4="$(printf '%s\n' "$v4" | grep -c '/')"
n6="$(printf '%s\n' "$v6" | grep -c '/')"
if [ "$n4" -lt 10 ] || [ "$n6" -lt 3 ]; then
  echo "cloudflare-ips: implausible lists (v4=$n4 v6=$n6); not writing $OUT" >&2
  exit 2
fi

ranges="$(printf '%s\n%s\n' "$v4" "$v6" | grep '/' | tr '\n' ' ' | sed 's/ *$//')"
new="# Generated by scripts/cloudflare-ips.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ) — do not edit.
# Imported by /etc/caddy/Caddyfile; every Cloudflare IPv4 and IPv6 range.
trusted_proxies static $ranges
"

if [ -f "$OUT" ] && [ "$(grep '^trusted_proxies' "$OUT" || true)" = "trusted_proxies static $ranges" ]; then
  echo "cloudflare-ips: unchanged ($n4 IPv4 + $n6 IPv6 ranges)"
  exit 0
fi

if [ "$MODE" = "--check" ]; then
  echo "cloudflare-ips: would write $OUT with $n4 IPv4 + $n6 IPv6 ranges"
  exit 0
fi

tmp="$(mktemp)"
printf '%s' "$new" > "$tmp"
install -m 0644 "$tmp" "$OUT"
rm -f "$tmp"
echo "cloudflare-ips: wrote $OUT ($n4 IPv4 + $n6 IPv6 ranges)"

if [ "$MODE" != "--no-reload" ] && [ -f /etc/caddy/Caddyfile ] && grep -q 'cloudflare-ips.caddy' /etc/caddy/Caddyfile; then
  caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile > /dev/null
  systemctl reload caddy
  echo "cloudflare-ips: caddy reloaded"
fi
