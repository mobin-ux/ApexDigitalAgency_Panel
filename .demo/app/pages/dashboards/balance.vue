/**
 * Expenses — the total and its parts, or the total alone. Never both sources.
 *
 * This card used to contradict itself on screen: the headline rendered the
 * API's real `totalSpent` while the breakdown beside it rendered a hardcoded
 * £3,200 / £3,100 / £1,940 array. A customer who spots a total that disagrees
 * with its own parts stops trusting every other number in the panel.
 *
 * `Transaction` is the money-truth and gives the headline. Per-project
 * attribution only exists on the installment plans, and `installmentPlan.paid`
 * is a counter that is not guaranteed to be ledger-backed — seeded or
 * adjusted plans can carry a `paid` value with no matching transaction. So the
 * breakdown is rendered only when the plans provably add up to the ledger
 * total; otherwise the card shows the honest total on its own.
 *
 * TODO(api): a ledger-derived per-project figure on /api/dashboard/stats
 * (sum of `Transaction` rows grouped by the owning project) would let the
 * breakdown render unconditionally and retire this reconciliation guard.
 */
const { data: ordersData } = await useFetch('/api/orders', { lazy: true })

const EXPENSE_TONES = ['bg-primary-500', 'bg-primary-400', 'bg-primary-300', 'bg-primary-200', 'bg-primary-100']

interface ExpenseRow { label: string, value: number, months: number, class: string }

// Paid-to-date per project, biggest first. Candidate parts, not yet trusted.
const planRows = computed(() =>
  ((ordersData.value as any)?.data ?? [])
    .map((project: any) => ({
      label: project.name as string,
      value: (project.installmentPlan?.paid ?? 0) as number,
      months: (project.installmentPlan?.monthsPaid ?? 0) as number,
    }))
    .filter((row: any) => row.value > 0)
    .sort((a: any, b: any) => b.value - a.value) as Omit<ExpenseRow, 'class'>[],
)

const expenseTotal = computed(() => stats.value.totalSpent)
const planTotal = computed(() => planRows.value.reduce((sum, row) => sum + row.value, 0))

// Sub-penny tolerance: these are floats that have been through monthly division.
const partsReconcile = computed(() =>
  planRows.value.length > 0 && Math.abs(planTotal.value - expenseTotal.value) < 0.01,
)

const expenses = computed<ExpenseRow[]>(() =>
  partsReconcile.value
    ? planRows.value.map((row, index) => ({ ...row, class: EXPENSE_TONES[index % EXPENSE_TONES.length]! }))
    : [],
)

function plural(count: number, word: string) {
  return `${count} ${word}${count === 1 ? '' : 's'}`
}

const expenseCaption = computed(() => {
  if (!expenses.value.length) {
    return 'Everything you have paid through Apex so far'
  }
  const months = planRows.value.reduce((sum, row) => sum + row.months, 0)
  return `${plural(months, 'installment')} across ${plural(expenses.value.length, 'project')}`
})

const expenseLegend = computed(() =>
  expenses.value.map(row => `${formatCurrency(row.value)} ${row.label}`).join(', '),
)

