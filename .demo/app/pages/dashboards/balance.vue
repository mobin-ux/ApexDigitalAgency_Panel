    case 'Pending':
      return { label: 'Pending', text: 'text-[#F2C14E]', chip: 'bg-[#D9A521]/14', bar: 'bg-[#F2C14E]' }
    default:
      return { label: 'Started', text: 'text-primary-400', chip: 'bg-primary-500/16', bar: 'bg-primary-500' }
  }
}

const VIOLET_BLOB = 'radial-gradient(circle at 50% 38%, #9b79f6 0%, #7d53f2 55%, #6c40e8 100%)'
