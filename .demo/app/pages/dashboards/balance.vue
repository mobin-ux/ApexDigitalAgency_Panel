function statusMeta(status: string) {
  switch (status) {
    case 'In Progress':
      return { label: 'In progress', text: 'text-[#22B07D]', chip: 'bg-[#22B07D]/15', bar: 'bg-[#22B07D]' }
    case 'Completed':
