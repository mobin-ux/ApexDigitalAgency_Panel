 * Every figure on this page is real: wallet balance, active count and project
 * rows from /api/dashboard/stats, the credit line from the CreditLine record on
 * that same payload, and the expense breakdown from the installment plans on
 * /api/orders. The only decoration left is the promo's growth card, which is
 * labelled as an example so it cannot be read as this account's own figure.
 */
definePageMeta({
  title: 'Dashboard',
  layout: 'sidenav',
  middleware: 'auth',
})

const { user } = useUser()
const { formatCurrency } = useCurrency()

const showPromo = ref(true)
const howOpen = ref(false)

const { data } = await useFetch('/api/dashboard/stats')

const firstName = computed(() =>
  user.value?.firstName || (user.value?.email ? user.value.email.split('@')[0] : 'there'),
)

const stats = computed(() => data.value?.stats ?? { activeProjects: 0, walletBalance: 0, adCredits: 0, totalSpent: 0 })
const projects = computed(() => data.value?.projects ?? [])

/**
 * Credit line — the real `CreditLine` record, not a quoted figure.
 *
 * This card used to hard-code a £12,500 limit and a green "Approved" chip in
 * the front end. That is a credit facility with terms, generated by a template:
 * it has to come from the record or not be shown at all. The record is `null`
 * until the customer applies, so the card has four honest states instead of
 * one fabricated one.
 */
const creditLine = computed<any>(() => (data.value as any)?.credit ?? null)
const credit = computed(() => {
  const line = creditLine.value
  const limit = line?.limit ?? 0
  const used = line?.used ?? 0
  return {
    status: (line?.status ?? 'NONE') as 'NONE' | 'PENDING' | 'ACTIVE' | 'FROZEN' | 'REJECTED',
    limit,
    used,
    available: Math.max(0, limit - used),
    // Clamped: an over-limit account (used > limit, which the ledger does
    // allow) would otherwise ask the bar to draw past its own track.
    pct: limit > 0 ? Math.min(100, Math.round((used / limit) * 100)) : 0,
  }
})

